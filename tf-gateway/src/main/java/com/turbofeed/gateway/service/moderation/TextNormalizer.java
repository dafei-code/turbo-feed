    private static final int FOLD_MISMATCH_COUNT = checkFoldDirection();

    /**
     * 方向自检：把 {@link #MUST_FOLD} 里的繁体字喂给映射，断言折叠结果等于期望的简体字。
     *
     * <p>用 {@code getOrDefault(c, c)} 而不是 {@code get(c)}：像「博」「警」这类
     * <b>繁简同形</b>的字本来就不该出现在映射表里，其期望值就是自身。
     * 若断言写成「必须查到映射」，这些样本会永远误报。</p>
     *
     * <p>能抓到的错误：把「繁→简」写成「简→繁」——此时查 {@code '測'} 会回落成 {@code '測'}，
     * 与期望的 {@code '测'} 不符，计数非 0。这类错误会让简体文本被转成繁体，
     * <b>所有简体词条全部漏放</b>，是灾难级且极难靠观察发现的，必须由自检挡住。</p>
     */
    private static int checkFoldDirection() {
        int bad = 0;
        for (String[] expect : MUST_FOLD) {
            char got = TRAD_TO_SIMP.getOrDefault(expect[0].charAt(0), expect[0].charAt(0));
            if (got != expect[1].charAt(0)) {
                bad++;
            }
        }
        return bad;
    }

