    private static final Map<Character, Character> TRAD_TO_SIMP = buildTradToSimp();

    /**
     * 构建映射并做<b>编码自检</b>：条目必须是 2 个字符且两字相异。
     *
     * <p>违反的条目会被跳过并<b>记录具体样本</b>（由 {@link #invalidPairSamples()} 暴露）。
     * 只报「有 N 条非法」是不够的——手工维护几百条映射时，「哪一条错了」才是可执行信息。
     * 样本上限 {@value #MAX_INVALID_SAMPLES} 条，避免刷屏。</p>
     */
    private static Map<Character, Character> buildTradToSimp() {
        Map<Character, Character> m = new HashMap<>(TRAD_SIMP_PAIRS.length * 2);
        List<String> invalid = new ArrayList<>(4);
        for (String pair : TRAD_SIMP_PAIRS) {
            if (pair == null || pair.length() != 2 || pair.charAt(0) == pair.charAt(1)) {
                if (invalid.size() < MAX_INVALID_SAMPLES) {
                    invalid.add(pair == null ? "<null>" : pair);
                }
                invalidTotal++;
                continue;
            }
            m.put(pair.charAt(0), pair.charAt(1));
        }
        INVALID_PAIRS = List.copyOf(invalid);
        return m;
    }

