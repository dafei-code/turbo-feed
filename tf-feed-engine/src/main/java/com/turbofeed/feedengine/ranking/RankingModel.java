package com.turbofeed.feedengine.ranking;

/**
 * 精排模型（可插拔打分器）。
 *
 * <p><b>为什么现在就要抽成一个接口</b>：当前的排序是一条硬编码在 {@code FeedTimelineStore}
 * 里的线性算式。要走向"模型化"（双塔 / DeepFM / 远程推理服务），第一件事不是选模型，
 * 而是<b>先把打分开槽，让它可被替换</b>——否则每换一次打分方式就要动读路径主流程，
 * 风险和review成本都由最热的一段代码承担。接口本身很薄：{@code 特征进 → 分值出}，
 * 足以承载从"线性公式"到"远程模型调用"的全部演进。</p>
 *
 * <p><b>契约约束</b>：
 * <ul>
 *   <li><b>分值越大越靠前</b>：调用方按降序排，实现类不要返回"越小越好"的距离/损失量；</li>
 *   <li><b>不得有副作用、不得抛业务异常</b>：它是排序的热路径，单条内容算不出来应当
 *   退化为保守分值（如纯 recency），而不是让整个推荐页失败；</li>
 *   <li><b>同一份输入必须得到同一份输出</b>（幂等/确定性）：便于回归验证与问题复现。</li>
 * </ul>
 * </p>
 */
public interface RankingModel {

    /**
     * 给一条候选打分（越大越靠前）。
     *
     * @param features 该候选的排序特征（含原始计数，供置信度平滑使用）
     * @return 排序分值
     */
    double score(RankingFeatures features);
}
